"""docs/BENCHMARKS.md section 4c: the refinery suite, SANKHYA against HiGHS and SCIP (#1004).

Reads bench/results/head-to-head-refinery-<commit>.csv (compare.py --suite refinery) and
data/refinery/manifest.json, and renders: the suite itself (each model, its citation, its
three sizes with rows, columns, sha256 prefix and how the reference optimum is known), then
the solver table, the per-instance split and the failures through head_to_head_doc's own
functions, so the refinery numbers are graded and printed by the same code as Netlib's.
Correctness counts come first: the run is on a shared laptop and the times say so.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import head_to_head_doc  # noqa: E402
import perf_profile  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]
MANIFEST = REPO_ROOT / "data" / "refinery" / "manifest.json"
ORDER = ("crude_blend", "product_blend", "haverly_mccormick", "haverly_discrete", "unloading",
         "unit_modes", "multi_period", "two_stage", "distribution", "lot_sizing")
TITLES = {
    "crude_blend": "crude-oil blending LP",
    "product_blend": "product blending LP with RVP, octane and sulphur specifications",
    "haverly_mccormick": "Haverly pooling, McCormick relaxation LP",
    "haverly_discrete": "Haverly pooling with discrete pool set-points, MILP",
    "unloading": "crude unloading and tank scheduling MILP",
    "unit_modes": "unit modes with semi-continuous throughputs, MILP",
    "multi_period": "30-day multi-period production planning LP",
    "two_stage": "two-stage price-scenario LP",
    "distribution": "product distribution LP",
    "lot_sizing": "crude procurement lot-sizing MILP",
}
HOW = {"kkt-construction": "exact, KKT construction", "rational-simplex": "exact, rational simplex",
       "enumeration": "exact, enumeration + rational simplex",
       "wagner-whitin": "exact, Wagner-Whitin recursion", "cross-check": "HiGHS = SCIP"}


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))["instances"] if MANIFEST.exists() \
        else {}


def suite_table(manifest: dict) -> list[str]:
    out = ["| # | model | source | size | rows | columns | integer | SC | sha256 | reference "
           "| known by |", "|--:|---|---|---|---:|---:|---:|---:|---|---:|---|"]
    for number, model in enumerate(ORDER, start=1):
        for size in ("small", "medium", "large"):
            e = manifest.get(f"{model}_{size}")
            if e is None:
                continue
            ref = e.get("reference_objective")
            out.append(f"| {number} | {TITLES[model]} | {e['source']} | {size} | {e['rows']} "
                       f"| {e['columns']} | {e['integer']} | {e['semicontinuous']} "
                       f"| `{e['sha256'][:12]}` | {'-' if ref is None else f'{ref:.6g}'} "
                       f"| {HOW.get(e['reference_source'], e['reference_source'])} |")
    return out


def section(path: Path | None, sgm) -> str:
    manifest = load_manifest()
    out = ["**The suite.** Ten models of known structure, each from a published formulation, "
           "at three sizes, generated by `bench/refinery/generate.py` (seed 1) and pinned by "
           "sha256 in `data/refinery/manifest.json`. Where the formulation allows it the "
           "optimum is exact: a plan chosen first and the costs derived from the KKT "
           "conditions (the five LPs), a rational simplex over the written LP (the McCormick "
           "relaxation), every discrete choice solved by that simplex (the discrete pooling "
           "MILP), or the Wagner-Whitin recursion (lot sizing). The two scheduling MILPs have "
           "no such construction: their reference is recorded only where HiGHS and SCIP, each "
           "at a zero gap, prove the same optimum, and the manifest keeps both values. A MIP "
           "is matched within the 1e-4 relative gap every solver stops at.", ""]
    out += suite_table(manifest)
    out.append("")
    if path is None:
        out.append("No `head-to-head-refinery-*.csv` in `bench/results/`, so **no numbers are "
                   "stated for this suite**. Run `python bench/runners/compare.py --suite "
                   "refinery`.")
        return "\n".join(out)
    rows = head_to_head_doc.read_csv(path)
    if not rows:
        return "\n".join(out + [f"`{path.name}` is empty."])
    first = rows[0]
    instances = sorted({r["instance"] for r in rows})
    out += [f"Source CSV: `bench/results/{path.name}`  ",
            f"Commit `{first['git_commit']}` · machine `{first['machine']}`  ",
            f"{len(instances)} instances · time limit {float(first['time_limit']):g} s · "
            "1 thread per solver · every solver a separate process · **a shared laptop, so "
            "the times are indicative; the counts are the result**", ""]
    out += head_to_head_doc.solver_table(rows, sgm)
    out.append("")
    out += head_to_head_doc.per_instance_table(rows)
    solvers = [s for s in head_to_head_doc.ORDER
               if any(r["solver"] == s and r["status"] != "unsupported" for r in rows)]
    figure = perf_profile.write_figure("refinery", "Refinery suite: Dolan-More performance "
                                       "profile", rows, solvers)
    if figure is not None:
        out += [f"![Dolan-More performance profile, refinery suite](img/{figure.name})", ""]
    out += ["**Every instance, every solver** (status, the objective at the solver's point, "
            "its relative gap to the reference, the verifier's verdict, the solver's time):",
            "", "| instance | kind | reference | " + " | ".join(
                perf_profile.LABELS[s] for s in solvers) + " |",
            "|---|---|---:|" + "---|" * len(solvers)]
    by = {(r["instance"], r["solver"]): r for r in rows}
    for name in instances:
        cells = []
        for s in solvers:
            r = by.get((name, s))
            if r is None:
                cells.append("-")
                continue
            if r["status"] == "optimal":
                gap = float(r["relative_gap"]) if r["relative_gap"] else float("nan")
                verdict = ("verified" if r["independently_verified"] == "1" else "REJECTED")
                what = f"{float(r['point_objective']):.6g}, gap {gap:.1e}, {verdict}"
            else:
                what = r["status"]
            cells.append(f"{what}, {float(r['solver_seconds']):.2f} s"
                         if r["solver_seconds"] else what)
        e = manifest.get(name, {})
        ref = e.get("reference_objective")
        out.append(f"| `{name}` | {e.get('kind', '-')} | "
                   f"{'-' if ref is None else f'{ref:.6g}'} | " + " | ".join(cells) + " |")
    out.append("")
    named = head_to_head_doc.failures(rows)
    if named:
        out += ["Every run that did not count, by solver:", "", *named, ""]
    reasons = head_to_head_doc.rejections(rows)
    if reasons:
        out += ["What the verifier rejected:", "", *reasons, ""]
    return "\n".join(out)
